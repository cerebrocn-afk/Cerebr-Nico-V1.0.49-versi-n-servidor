import { config } from 'dotenv';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(app);
config({path:path.join(app,'.env')});
process.env.CN_SERVER_MODE = '1';
process.env.NODE_ENV = 'production';
process.env.HOST ||= '127.0.0.1';
if (!process.env.PROJECT_DIR?.trim()) throw new Error('Define PROJECT_DIR en un volumen persistente; no se permite un respaldo temporal silencioso.');
if (!process.env.ACCESS_TOKEN || process.env.ACCESS_TOKEN.length < 24) throw new Error('Define ACCESS_TOKEN con al menos 24 caracteres aleatorios.');
if (!process.env.CN_PUBLIC_ORIGIN) throw new Error('Define CN_PUBLIC_ORIGIN con el origen HTTPS de la IDE, sin barra final.');
const root=path.resolve(process.env.PROJECT_DIR);
const rel=path.relative(root,app);
if (!rel.startsWith('..') && !path.isAbsolute(rel)) throw new Error('El workspace no puede contener la instalación. Instala la IDE en una subcarpeta separada y usa /workspace/proyecto, o usa ./workspace.');
fs.mkdirSync(root,{recursive:true});
if (!fs.existsSync(path.join(app,'dist','server.mjs'))) throw new Error('Primero ejecuta npm run build.');
console.log('CerebróNico: edición servidor privada, workspace persistente y sesiones simples.');
await import(pathToFileURL(path.join(app,'dist','server.mjs')).href);
